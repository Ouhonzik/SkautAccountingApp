# Tvary, ve kterych datum narozeni doted chodilo. Import ho z Excelu zapisoval
# jako "22.05.2006", rucni oprava v tabulce mohla nechat cokoli jineho.
TVARY = ("%d.%m.%Y", "%d. %m. %Y", "%Y-%m-%d", "%d/%m/%Y", "%d.%m.%y")


def _na_iso(hodnota: str) -> str | None:
    """Text data narozeni na ISO. None, kdyz se precist neda."""
    text = " ".join(str(hodnota).split())
    for tvar in TVARY:
        try:
            return datetime.strptime(text, tvar).date().isoformat()
        except ValueError:
            continue
    return None


